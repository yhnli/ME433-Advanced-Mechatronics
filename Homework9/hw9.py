### helper filters ###
# read data
def read_csv(file_name, t, signal):
    with open(file_name) as f:
        # open the csv file
        reader = csv.reader(f)
        for row in reader:
            # read the rows 1 one by one
            t.append(float(row[0])) # leftmost column
            signal.append(float(row[1])) # second column

# fft
def calc_fft(t, signal):
    Fs = 10000
    Ts = 1.0/Fs
    ts = np.arange(0,t[-1],Ts)
    y = np.interp(ts, t, signal)
    n = len(y)
    k = np.arange(n)
    T = n/Fs
    frq = k/T
    frq = frq[range(int(n/2))]
    Y = np.fft.fft(y)/n
    Y = Y[range(int(n/2))]

    # plot
    fig, (ax1, ax2) = plt.subplots(2, 1)
    ax1.plot(ts, y, 'b')
    ax1.set_xlabel('Time')
    ax1.set_ylabel('Amplitude')
    ax2.loglog(frq, abs(Y), 'b')
    ax2.set_xlabel('Freq (Hz)')
    ax2.set_ylabel('|Y(freq)|')
    plt.show()

# moving average filter
def moving_avg_filter(signal, x):
    signal = np.asarray(signal, dtype=float)
    out = np.empty(len(signal))
    for i in range(len(signal)):
        start = max(0, i - x + 1)
        out[i] = signal[start : i + 1].mean()
    return out

# iir filter
def iir_filter(signal, A, B):
    sig_new = []
    y_prev = 0
    for i in range(len(signal)):
        y = A * signal[i] + (B) * y_prev
        sig_new.append(y)
        y_prev = y
    return sig_new

# fir filter
def fir_filter(signal, h):
    return np.convolve(np.asarray(signal, dtype=float), h, mode='full')[:len(signal)]

# plot filtered signal
def plot_filtered(time, original, filtered, title):
    Fs  = 10000
    Ts  = 1.0 / Fs
 
    # original fft
    ts_orig = np.arange(0, time[-1], Ts)
    y_orig  = np.interp(ts_orig, time, original)
    n_o     = len(y_orig)
    frq_o   = np.arange(n_o) / (n_o / Fs)
    frq_o   = frq_o[:n_o // 2]
    Y_o     = np.fft.fft(y_orig) / n_o
    Y_o     = Y_o[:n_o // 2]
 
    # filtered fft
    filt_arr = np.array(filtered)
    n_f      = len(filt_arr)
    frq_f    = np.arange(n_f) / (n_f / Fs)
    frq_f    = frq_f[:n_f // 2]
    Y_f      = np.fft.fft(filt_arr) / n_f
    Y_f      = Y_f[:n_f // 2]
 
    fig, (ax1, ax2) = plt.subplots(2, 1, figsize=(10, 8))
    fig.suptitle(title)
 
    ax1.plot(time, original, 'k', label='Unfiltered')
    ax1.plot(time[:len(filtered)], filtered, 'r', label='Filtered')
    ax1.set_xlabel('Time')
    ax1.set_ylabel('Amplitude')
    ax1.legend()
 
    ax2.loglog(frq_o, np.abs(Y_o), 'k', label='Unfiltered')
    ax2.loglog(frq_f, np.abs(Y_f), 'r', label='Filtered')
    ax2.set_xlabel('Freq (Hz)')
    ax2.set_ylabel('|Y(freq)|')
    ax2.legend()
 
    plt.tight_layout()
    plt.show()

